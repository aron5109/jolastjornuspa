const SIGNS_BY_ID = new Map<ZodiacId, ZodiacSign>(SIGNS.map((sign) => [sign.id, sign]));

export function getSign(id: ZodiacId): ZodiacSign {
  const sign = SIGNS_BY_ID.get(id);
  if (!sign) throw new Error(`Unknown zodiac sign: ${id}`);
  return sign;
}

export function isZodiacId(value: string | null | undefined): value is ZodiacId {
  return !!value && SIGNS_BY_ID.has(value as ZodiacId);
}
